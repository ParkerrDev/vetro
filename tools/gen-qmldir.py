#!/usr/bin/env python3
"""Write a qmldir in every directory of Vetro's QML libraries that holds QML.

Quickshell registers `pragma Singleton` files by itself only inside the
shell's own directory. Omarchy loads third-party plugins from
~/.config/omarchy/plugins, outside it, so each directory that a plugin imports
needs a qmldir naming its types, singletons marked as such. Those are the
library the shell plugins share (shell/vetro.lib) and the launch cards' own
types.

  tools/gen-qmldir.py            write the qmldir files
  tools/gen-qmldir.py --check    change nothing; exit 1 if any is missing or
                                 out of date (what the repository's checks run)
  tools/gen-qmldir.py DIR...     only these folders
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LIBRARIES = [
    os.path.join(ROOT, "shell", "vetro.lib"),
    os.path.join(ROOT, "addons", "launch", "plugin", "vetro.cards", "launch"),
]
HEADER = "# Generated by tools/gen-qmldir.py: every type here, singletons marked."


def qmldir_for(directory, names):
    """The text a directory's qmldir should have, or None if it has no QML."""
    qml = sorted(f for f in names if f.endswith(".qml") and f[0].isupper())
    if not qml:
        return None
    lines = [HEADER]
    for f in qml:
        with open(os.path.join(directory, f), encoding="utf-8") as fh:
            head = fh.read(400)
        singleton = re.search(r"^\s*pragma\s+Singleton\b", head, re.M) is not None
        lines.append(f"{'singleton ' if singleton else ''}{f[:-4]} 1.0 {f}")
    return "\n".join(lines) + "\n"


def main(argv):
    check = "--check" in argv
    roots = [a for a in argv if not a.startswith("--")] or LIBRARIES
    stale = []
    written = 0
    for root in roots:
        for directory, _, names in sorted(os.walk(root)):
            want = qmldir_for(directory, names)
            if want is None:
                continue
            path = os.path.join(directory, "qmldir")
            have = None
            if os.path.exists(path):
                with open(path, encoding="utf-8") as fh:
                    have = fh.read()
            if have == want:
                continue
            if check:
                stale.append(os.path.relpath(path, ROOT))
            else:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(want)
                written += 1
    if check:
        for path in stale:
            print(f"gen-qmldir: {path} is missing or out of date", file=sys.stderr)
        return 1 if stale else 0
    print(f"wrote {written} qmldir files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
